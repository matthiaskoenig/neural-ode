"""Markdown report of a test suite run (`docs/testsuite.md`)."""

import re
from collections import Counter, defaultdict

from sbml2jax.testsuite.results import CATEGORIES, STAGES, STATUSES, CaseResult
from sbml2jax.testsuite.runner import ATOL, RTOL


def reason(message: str) -> str:
    """Return the failure reason of a message, without case specific details."""
    message = message.split(";")[0]
    message = re.sub(r"'[^']*'", "'…'", message)
    message = re.sub(r"\b[A-Za-z_]\w* exceeds the tolerance by .*", "exceeds the tolerance", message)
    message = re.sub(r"\(.*\)", "", message)
    return message.strip()


def render(results: list[CaseResult]) -> str:
    """Return the report of `results`."""
    lines = [
        "# SBML test suite",
        "",
        "Every semantic case of the [SBML test suite](https://github.com/sbmlteam/sbml-test-suite)"
        " is simulated with roadrunner (`roadrunner`), converted to a JAX module (`sbml2jax`) and"
        " simulated with diffrax (`jax`); both simulations are compared with the expected results"
        " of the case with the tolerances of the case. Solver tolerances of both simulators:"
        f" relative {RTOL:g}, absolute {ATOL:g}.",
        "",
        "Generated by `sbml2jax-testsuite run`, do not edit.",
        "",
        "Categories: `pass` converted and the JAX simulation matches, `fail` converted but the"
        " simulation does not match, `unsupported` the conversion failed (see"
        " [conversion issues](conversion-issues.md)), `skip` out of scope of the test.",
        "",
        "| " + " | ".join(CATEGORIES) + " | total |",
        "|" + " --- |" * (len(CATEGORIES) + 1),
        "| "
        + " | ".join(str(sum(r.category == c for r in results)) for c in CATEGORIES)
        + f" | {len(results)} |",
        "",
        "Status per stage:",
        "",
        "| stage | " + " | ".join(STATUSES) + " |",
        "| --- |" + " --- |" * len(STATUSES),
    ]
    for stage in STAGES:
        counts = Counter(r.stages[stage].status for r in results if stage in r.stages)
        lines.append(f"| `{stage}` | " + " | ".join(str(counts.get(s, 0)) for s in STATUSES) + " |")

    for stage in STAGES:
        groups: dict[str, list[str]] = defaultdict(list)
        for r in results:
            result = r.stages.get(stage)
            if result is not None and result.status != "pass":
                groups[f"{result.status}: {reason(result.message)}"].append(r.id)
        if not groups:
            continue
        lines += ["", f"## `{stage}`: failures and skips by reason", ""]
        lines += ["| reason | cases | ids |", "| --- | --- | --- |"]
        for key, ids in sorted(groups.items(), key=lambda kv: -len(kv[1])):
            shown = ", ".join(ids[:15]) + (", …" if len(ids) > 15 else "")
            lines.append(f"| {key.replace('|', '/')} | {len(ids)} | {shown} |")
    return "\n".join(lines) + "\n"
